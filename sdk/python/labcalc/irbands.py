def expected(group: str) -> list[dict]:
    """Erwartete Banden einer Gruppe: [{ids, lo, hi, name}] – Bereich = Vereinigung der Alternativen."""
    out = []
    for alts in GROUP_BANDS.get(group, ([], None))[0]:
        ts = [_ID[i] for i in alts]
        out.append({"ids": list(alts), "lo": min(min(t[1], t[2]) for t in ts), "hi": max(max(t[1], t[2]) for t in ts),
                    "name": " / ".join(t[5] for t in ts), "name_en": " / ".join(t[6] for t in ts),
                    "strength": ts[0][3]})
    return out
