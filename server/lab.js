'use strict';
// Report side of Folio Lab: stores analysis bundles ("folio-lab-bundle/1") in a project.
//
//   lab/labdata.tex          \labset / \labval macros plus \input of every bundle's values (regenerated)
//   lab/references.bib       all citations of all bundles, de-duplicated (regenerated)
//   lab/<slug>/bundle.json   manifest: items, captions, labels, values, source request
//   lab/<slug>/...           figures (PDF + PNG preview), tables (.tex), data (.csv), text, values.tex, refs.bib
//   lab/<slug>/source/...    the raw measurement files, so the module can rebuild the bundle (Refresh)
//
// The hub never edits the user's own .tex files; the editor inserts \input lines and snippets.
const crypto = require('crypto');
const fsp = require('fs').promises;
const path = require('path');
const { HttpError, exists } = require('./util');
const P = require('./projects');
const modules = require('./modules');

const FORMAT = 'folio-lab-bundle/1';
// Folio Lab suite version (package.json), recorded with every result next to the module version.
const SUITE_VERSION = (() => {
  try {
    return require('../package.json').version || null;
  } catch {
    return null;
  }
})();
const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,59}$/;
const FILE_RE = /^[A-Za-z0-9_][A-Za-z0-9_.\-/]{0,120}$/;

const LABDATA = String.raw`% Folio Lab: values handed over from analysis modules.
% \labval{<bundle>}{<key>} prints a value; each lab/<bundle>/values.tex defines them with \labset.
% Regenerated by Folio Lab whenever results change; do not edit. Include it once: \input{lab/labdata}
\makeatletter
\providecommand\labset[3]{\expandafter\gdef\csname labv@#1@#2\endcsname{#3}}
\providecommand\labval[2]{\@ifundefined{labv@#1@#2}{\textbf{??}\PackageWarning{folio-lab}{Value #1/#2 undefined}}{\csname labv@#1@#2\endcsname}}
\makeatother
`;

const labDir = (id) => path.join(P.filesDir(id), 'lab');

function checkSlug(slug) {
  if (!SLUG_RE.test(String(slug || ''))) throw new HttpError(400, 'Invalid bundle name');
  return slug;
}

async function readManifest(id, slug) {
  try {
    return JSON.parse(await fsp.readFile(path.join(labDir(id), checkSlug(slug), 'bundle.json'), 'utf8'));
  } catch (e) {
    if (e.status) throw e;
    throw new HttpError(404, `Bundle "${slug}" not found`);
  }
}

async function list(id) {
  await P.readMeta(id);
  let dirs = [];
  try {
    dirs = (await fsp.readdir(labDir(id), { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name);
  } catch {
    return [];
  }
  const out = [];
  for (const d of dirs) {
    if (!SLUG_RE.test(d)) continue;
    try {
      const m = await readManifest(id, d);
      m.revision = m.revision || 1;
      m.history_count = (await revisionNumbers(path.join(labDir(id), d))).length;
      m.refs = refsOf(m); // UI-09: status chip "uses shared input"
      out.push(m);
    } catch {
      /* folder without manifest */
    }
  }
  out.sort((a, b) => String(b.updated || '').localeCompare(String(a.updated || '')));
  return out;
}

/** Regenerate lab/references.bib (all refs.bib, first entry per key wins) and lab/labdata.tex. */
async function rebuildReferences(id) {
  const seen = new Set();
  const parts = ['% Generated by Folio Lab from the analysis bundles in lab/. Do not edit; edits are overwritten.\n'];
  for (const b of await list(id)) {
    let txt = '';
    try {
      txt = await fsp.readFile(path.join(labDir(id), b.slug, 'refs.bib'), 'utf8');
    } catch {
      continue;
    }
    for (const entry of txt.split(/\n(?=@)/)) {
      const m = /^\s*@\w+\s*\{\s*([^,\s]+)\s*,/.exec(entry);
      if (!m || seen.has(m[1])) continue;
      seen.add(m[1]);
      parts.push(entry.trim() + '\n');
    }
  }
  await fsp.mkdir(labDir(id), { recursive: true });
  await fsp.writeFile(path.join(labDir(id), 'references.bib'), parts.join('\n'));
  const inputs = (await list(id)).filter((b) => (b.files || []).includes('values.tex')).map((b) => `\\InputIfFileExists{lab/${b.slug}/values}{}{}% ${String(b.title).replace(/[\r\n]+/g, ' ')}`);
  await fsp.writeFile(path.join(labDir(id), 'labdata.tex'), LABDATA + inputs.join('\n') + '\n');
}

async function uniqueSlug(id, base) {
  let s = base;
  for (let n = 2; await exists(path.join(labDir(id), s)); n++) s = `${base.slice(0, 55)}-${n}`;
  return s;
}

/**
 * Store a bundle. mode: undefined -> 409 if the name is taken, 'replace' -> overwrite, 'new' -> pick a free name.
 * Returns the manifest.
 */
async function save(id, bundle, mode, info) {
  await P.readMeta(id);
  if (!bundle || bundle.format !== FORMAT) throw new HttpError(400, `Not a ${FORMAT} bundle`);
  let slug = checkSlug(bundle.slug);
  const dir = path.join(labDir(id), slug);
  if (await exists(dir)) {
    if (mode === 'new') slug = await uniqueSlug(id, slug);
    else if (mode !== 'replace') {
      const old = await readManifest(id, slug).catch(() => ({}));
      throw Object.assign(new HttpError(409, `A result named "${slug}" already exists`), { body: { exists: true, slug, title: old.title } });
    }
  }
  const files = bundle.files || {};
  for (const rel of Object.keys(files)) {
    if (!FILE_RE.test(rel) || rel.includes('..') || rel.startsWith('source/') || rel === 'bundle.json')
      throw new HttpError(400, `Invalid file name in bundle: ${rel}`);
  }
  const srcFiles = (bundle.source && bundle.source.files) || {};
  for (const name of Object.keys(srcFiles)) {
    if (!/^[^\\/:*?"<>|]{1,120}$/.test(name) || name.includes('..')) throw new HttpError(400, `Invalid source file name: ${name}`);
  }

  const target = path.join(labDir(id), slug);
  // A1: a replaced result keeps its previous revision under history/<n>/ (old bundles without the field count as 1).
  const prev = mode === 'replace' && slug === bundle.slug ? await readManifest(id, slug).catch(() => null) : null;
  let history = [];
  if (prev) {
    history = await revisionNumbers(target);
    await archiveCurrent(target, prev.revision || 1);
  } else {
    await fsp.rm(target, { recursive: true, force: true });
  }
  await fsp.mkdir(target, { recursive: true });
  for (const [rel, b64] of Object.entries(files)) {
    const abs = path.join(target, rel);
    await fsp.mkdir(path.dirname(abs), { recursive: true });
    await fsp.writeFile(abs, Buffer.from(b64, 'base64'));
  }
  for (const [name, b64] of Object.entries(srcFiles)) {
    await fsp.mkdir(path.join(target, 'source'), { recursive: true });
    await fsp.writeFile(path.join(target, 'source', name), Buffer.from(b64, 'base64'));
  }

  // Items carry labels with the original slug; keep them in step with a renamed bundle.
  const relabel = (s) => (slug === bundle.slug ? s : String(s).replace(`:${bundle.slug}-`, `:${slug}-`));
  const items = (bundle.items || []).map((it) => (it.label ? { ...it, label: relabel(it.label) } : it));
  if (slug !== bundle.slug && files['values.tex']) {
    const vp = path.join(target, 'values.tex');
    const txt = (await fsp.readFile(vp, 'utf8')).split(`\\labset{${bundle.slug}}`).join(`\\labset{${slug}}`).split(`\\labval{${bundle.slug}}`).join(`\\labval{${slug}}`);
    await fsp.writeFile(vp, txt);
  }
  if (slug !== bundle.slug) {
    for (const rel of Object.keys(files).filter((f) => /^text-.*\.tex$/.test(f))) {
      const tp = path.join(target, rel);
      const txt = await fsp.readFile(tp, 'utf8');
      await fsp.writeFile(tp, txt.split(`{${bundle.slug}}`).join(`{${slug}}`).split(`:${bundle.slug}-`).join(`:${slug}-`));
    }
  }

  // Module version: the version the computing module reports in its bundle (the running process, which can be older
  // than module.json on disk until the hub restarts it); only when a bundle carries none, module.json read now.
  const mod = bundle.module_version ? null : await modules.get(bundle.module).catch(() => null);
  const moduleVersion = bundle.module_version || (mod && mod.version) || null;
  const moduleVersionFrom = bundle.module_version ? 'bundle' : mod && mod.version ? 'module.json' : null;
  // source_sha256: SHA-256 of each file stored under lab/<slug>/source/, i.e. exactly what the module gets back on
  // Refresh. For measurement modules these are the raw files; for the Datenaufbereitung it is the dataset version
  // (datensatz.json), not the raw file behind it (that hash is in the dataset provenance). bundle.source.kind says which.
  const sha = {};
  for (const [name, b64] of Object.entries(srcFiles)) sha[name] = crypto.createHash('sha256').update(Buffer.from(b64, 'base64')).digest('hex');
  const manifest = {
    format: FORMAT,
    module: bundle.module,
    module_name: bundle.module_name,
    title: bundle.title,
    slug,
    lang: bundle.lang,
    summary: bundle.summary || '',
    created: (prev && prev.created) || bundle.created,
    updated: new Date().toISOString(),
    items,
    files: Object.keys(files).sort(),
    source: bundle.source && bundle.source.request ? { request: { ...bundle.source.request, slug }, files: Object.keys(srcFiles) } : null,
    // provenance: which software version produced the result from which input files
    result_id: (prev && prev.result_id) || crypto.randomUUID(),
    revision: prev ? Math.max(prev.revision || 1, ...history) + 1 : 1,
    provenance: {
      suite_version: SUITE_VERSION,
      module_id: bundle.module,
      module_version: moduleVersion,
      module_version_from: moduleVersionFrom,
      methods: bundle.methods || null,
      source_sha256: sha,
      source_kind: (bundle.source && typeof bundle.source.kind === 'string' && bundle.source.kind.slice(0, 40)) || (Object.keys(sha).length ? 'files' : null),
      action: (info && info.action) || (prev ? 'replace' : 'new'),
    },
    issued: null,
  };
  await fsp.writeFile(path.join(target, 'bundle.json'), JSON.stringify(manifest, null, 2));
  await rebuildReferences(id);
  await P.touch?.(id);
  return manifest;
}

/** Ask the module to rebuild a bundle from its stored source files and settings. */
async function refresh(id, slug, opts = {}) {
  const man = await readManifest(id, slug);
  if (!man.source || !man.source.request) throw new HttpError(400, 'This result has no stored source and cannot be refreshed');
  const files = {};
  for (const name of man.source.files || []) {
    files[name] = (await fsp.readFile(path.join(labDir(id), slug, 'source', name))).toString('base64');
  }
  const m = await modules.get(man.module);
  const endpoint = (m.bundle && m.bundle.rebuild) || '/api/bundle/rebuild';
  const body = { source: { request: { ...man.source.request, slug }, files } };
  if (opts.lang) body.lang = opts.lang;
  const fresh = await modules.call(man.module, endpoint, body);
  fresh.slug = slug;
  return save(id, fresh, 'replace', { action: opts.lang ? 'language' : 'refresh' });
}

// ---------------------------------------------------------------- A1 revisions
const HIST = 'history';

/** Numbers of the stored old revisions of a bundle folder. */
async function revisionNumbers(dir) {
  try {
    return (await fsp.readdir(path.join(dir, HIST), { withFileTypes: true }))
      .filter((d) => d.isDirectory() && /^\d+$/.test(d.name))
      .map((d) => +d.name)
      .sort((a, b) => a - b);
  } catch {
    return [];
  }
}

/** Move everything but history/ into history/<rev>/. */
async function archiveCurrent(dir, rev) {
  const dest = path.join(dir, HIST, String(rev));
  await fsp.rm(dest, { recursive: true, force: true });
  await fsp.mkdir(dest, { recursive: true });
  for (const e of await fsp.readdir(dir)) {
    if (e === HIST) continue;
    await fsp.rename(path.join(dir, e), path.join(dest, e));
  }
}

async function manifestOf(id, slug, rev) {
  const cur = await readManifest(id, slug);
  if (rev == null || +rev === (cur.revision || 1)) return { man: cur, dir: path.join(labDir(id), slug) };
  if (!/^\d+$/.test(String(rev))) throw new HttpError(400, 'Invalid revision');
  const dir = path.join(labDir(id), slug, HIST, String(+rev));
  try {
    return { man: JSON.parse(await fsp.readFile(path.join(dir, 'bundle.json'), 'utf8')), dir };
  } catch {
    throw new HttpError(404, `Revision ${rev} of "${slug}" not found`);
  }
}

/** All revisions, newest first: {revision, updated, title, issued, current, action, module_version}. */
async function revisions(id, slug) {
  const cur = await readManifest(id, slug);
  const row = (m, current) => ({
    revision: m.revision || 1, updated: m.updated, title: m.title, lang: m.lang, issued: m.issued || null, current,
    action: (m.provenance && m.provenance.action) || null, module_version: (m.provenance && m.provenance.module_version) || null,
  });
  const out = [row(cur, true)];
  for (const n of await revisionNumbers(path.join(labDir(id), slug))) {
    try {
      out.push(row((await manifestOf(id, slug, n)).man, false));
    } catch {
      /* broken history folder */
    }
  }
  return out.sort((a, b) => b.revision - a.revision);
}

async function hashFile(p) {
  try {
    return crypto.createHash('sha256').update(await fsp.readFile(p)).digest('hex');
  } catch {
    return null;
  }
}

/** What changed between two revisions: values, items, files, source files and module version. */
async function compare(id, slug, a, b) {
  const A = await manifestOf(id, slug, a);
  const B = await manifestOf(id, slug, b);
  const vals = (m) => new Map(m.items.filter((i) => i.kind === 'values').flatMap((i) => i.values || []).map((v) => [v.key, v]));
  const va = vals(A.man);
  const vb = vals(B.man);
  const values = [];
  for (const k of new Set([...va.keys(), ...vb.keys()])) {
    const x = va.get(k);
    const y = vb.get(k);
    const tx = x ? x.text || x.latex : null;
    const ty = y ? y.text || y.latex : null;
    if (tx !== ty) values.push({ key: k, label: (y || x).label, a: tx, b: ty });
  }
  const ids = (m) => new Set(m.items.filter((i) => i.id).map((i) => `${i.kind}:${i.id}`));
  const ia = ids(A.man);
  const ib = ids(B.man);
  const files = { changed: [], added: [], removed: [] };
  for (const f of new Set([...(A.man.files || []), ...(B.man.files || [])])) {
    const inA = (A.man.files || []).includes(f);
    const inB = (B.man.files || []).includes(f);
    if (inA && !inB) files.removed.push(f);
    else if (!inA && inB) files.added.push(f);
    else if ((await hashFile(path.join(A.dir, f))) !== (await hashFile(path.join(B.dir, f)))) files.changed.push(f);
  }
  const sa = (A.man.provenance && A.man.provenance.source_sha256) || null;
  const sb = (B.man.provenance && B.man.provenance.source_sha256) || null;
  return {
    a: A.man.revision || 1, b: B.man.revision || 1, values,
    items: { added: [...ib].filter((x) => !ia.has(x)), removed: [...ia].filter((x) => !ib.has(x)) },
    files,
    source_changed: sa && sb ? JSON.stringify(sa) !== JSON.stringify(sb) : null,
    module_version: [(A.man.provenance || {}).module_version || null, (B.man.provenance || {}).module_version || null],
    lang: [A.man.lang, B.man.lang],
  };
}

/** Restore an old revision as a new one; the current one goes to history first, nothing is lost. */
async function restore(id, slug, rev) {
  const cur = await readManifest(id, slug);
  const curRev = cur.revision || 1;
  if (+rev === curRev) throw new HttpError(400, `Revision ${rev} is already the current one`);
  const { man, dir: src } = await manifestOf(id, slug, rev);
  const target = path.join(labDir(id), slug);
  const nums = await revisionNumbers(target);
  const tmp = path.join(labDir(id), `.restore-${slug}-${Date.now()}`);
  await fsp.cp(src, tmp, { recursive: true });
  await archiveCurrent(target, curRev);
  for (const e of await fsp.readdir(tmp)) await fsp.rename(path.join(tmp, e), path.join(target, e));
  await fsp.rm(tmp, { recursive: true, force: true });
  const out = {
    ...man, slug, result_id: cur.result_id || man.result_id || crypto.randomUUID(), revision: Math.max(curRev, ...nums) + 1,
    updated: new Date().toISOString(), issued: null,
    provenance: { ...(man.provenance || {}), action: 'restore', restored_from: +rev },
  };
  await fsp.writeFile(path.join(target, 'bundle.json'), JSON.stringify(out, null, 2));
  await rebuildReferences(id);
  return out;
}

/** Mark the current revision issued (fixed); how = 'manual' | 'pdf' | 'zip'. Old bundles get their fields now. */
async function issue(id, slug, how = 'manual') {
  const man = await readManifest(id, slug);
  if (man.issued) return man;
  man.revision = man.revision || 1;
  man.result_id = man.result_id || crypto.randomUUID();
  man.issued = { at: new Date().toISOString(), how };
  await fsp.writeFile(path.join(labDir(id), slug, 'bundle.json'), JSON.stringify(man, null, 2));
  return man;
}

/** Q22 a): exporting the PDF or ZIP fixes the current revision of every result in the report. */
async function issueAll(id, how) {
  for (const b of await list(id)) await issue(id, b.slug, how);
}

// A8 retention: a result with an issued revision (current or in history/) is not deleted but moved, with all its
// files, to lab/_removed/<slug>-<time>/. It no longer appears in the report (list() skips the folder), but the shared
// versions it names stay protected (sdk/python/labprov.py reads lab/_removed/ too). Results never issued are deleted.
const REMOVED = '_removed';

async function wasIssued(dir) {
  const read = async (p) => {
    try {
      return JSON.parse(await fsp.readFile(p, 'utf8'));
    } catch {
      return null;
    }
  };
  const cur = await read(path.join(dir, 'bundle.json'));
  if (cur && cur.issued) return true;
  for (const n of await revisionNumbers(dir)) {
    const m = await read(path.join(dir, HIST, String(n), 'bundle.json'));
    if (m && m.issued) return true;
  }
  return false;
}

async function remove(id, slug) {
  await P.readMeta(id);
  const dir = path.join(labDir(id), checkSlug(slug));
  if (!(await exists(dir))) throw new HttpError(404, `Bundle "${slug}" not found`);
  let kept = null;
  if (await wasIssued(dir)) {
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    kept = path.join(labDir(id), REMOVED, `${slug}-${stamp}`);
    await fsp.mkdir(path.dirname(kept), { recursive: true });
    await fsp.rename(dir, kept);
    const mp = path.join(kept, 'bundle.json');
    try {
      const m = JSON.parse(await fsp.readFile(mp, 'utf8'));
      m.removed = { at: new Date().toISOString(), reason: 'issued revision kept' };
      await fsp.writeFile(mp, JSON.stringify(m, null, 2));
    } catch {
      /* manifest unreadable: the folder is kept as it is */
    }
  } else {
    await fsp.rm(dir, { recursive: true, force: true });
  }
  await rebuildReferences(id);
  return { kept: kept ? path.relative(labDir(id), kept).split(path.sep).join('/') : null };
}

// ---------------------------------------------------------------- UI-09: history and dependencies
// Shared inputs and project-index values a stored request uses; same rule as sdk/python/labprov.py (_walk_refs).
const SHARE_RE = /^s-[0-9a-f]{8}$/;
const INDEX_RE = /^g-[0-9a-f]{8}$/;
function refsIn(o, out) {
  if (Array.isArray(o)) o.forEach((v) => refsIn(v, out));
  else if (o && typeof o === 'object') {
    if (o.schema === 'suite.shared-result/1' && SHARE_RE.test(String(o.id || ''))) out.shares.add(`${o.id} v${+o.version || 0}`);
    if (SHARE_RE.test(String(o.share || '')) && o.version != null && Number.isFinite(+o.version)) out.shares.add(`${o.share} v${+o.version}`);
    // binding {id, mode: pin|live|copy, version?, used?}: the version used counts
    if (['pin', 'live', 'copy'].includes(o.mode) && SHARE_RE.test(String(o.id || '')) && o.schema == null) {
      const v = o.used != null ? o.used : o.version;
      if (v != null && Number.isFinite(+v)) out.shares.add(`${o.id} v${+v}`);
    }
    if (INDEX_RE.test(String(o.index || ''))) out.index.add(o.index);
    Object.values(o).forEach((v) => refsIn(v, out));
  }
  return out;
}
function refsOf(man) {
  const r = refsIn(man && man.source ? man.source.request : null, { shares: new Set(), index: new Set() });
  return { shares: [...r.shares].sort(), index: [...r.index].sort() };
}

/** What one result rests on: module and version, measurement files with SHA-256, shared inputs and index values.
 *  The chain from a shared input back to its raw file comes from a module on demand (every module serves
 *  /api/prov/report); it is only asked when the result uses shared inputs or index values. */
async function history(id, slug) {
  const man = await readManifest(id, slug);
  const pv = man.provenance || {};
  const out = {
    slug, result_id: man.result_id || null, revision: man.revision || 1, title: man.title,
    module: man.module, module_name: man.module_name || man.module, module_version: pv.module_version || null,
    suite_version: pv.suite_version || null,
    action: pv.action || null, issued: man.issued || null, methods: pv.methods || null,
    source: Object.entries(pv.source_sha256 || {}).map(([name, sha256]) => ({ name, sha256 })),
    refs: refsOf(man), chains: [], chains_error: null,
  };
  if (out.refs.shares.length || out.refs.index.length) {
    try {
      out.chains = (await modules.call(man.module, '/api/prov/report', { report: id, slug })).chains || [];
    } catch (e) {
      out.chains_error = e.message;
    }
  }
  return out;
}

/** dependencies.json for the ZIP export: every result and kept revision with its module version, measurement
 *  file hashes and the shared versions / index values it used. Null when the report has no results. */
async function dependencies(id) {
  const results = [];
  for (const cur of await list(id)) {
    const mans = [cur];
    for (const n of await revisionNumbers(path.join(labDir(id), cur.slug))) {
      try {
        mans.push((await manifestOf(id, cur.slug, n)).man);
      } catch {
        /* broken history folder */
      }
    }
    for (const m of mans) {
      const pv = m.provenance || {};
      results.push({
        result: cur.slug, revision: m.revision || 1, current: m === cur, issued: m.issued || null, result_id: m.result_id || null,
        module: m.module, module_version: pv.module_version || null, suite_version: pv.suite_version || null,
        source_sha256: pv.source_sha256 || {}, ...refsOf(m),
      });
    }
  }
  // results removed from the report but kept because a revision was issued (lab/_removed/<slug>-<time>/)
  let removed = [];
  try {
    removed = (await fsp.readdir(path.join(labDir(id), REMOVED), { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name);
  } catch {
    /* none */
  }
  for (const d of removed) {
    const dir = path.join(labDir(id), REMOVED, d);
    const mans = [];
    try {
      mans.push(JSON.parse(await fsp.readFile(path.join(dir, 'bundle.json'), 'utf8')));
    } catch {
      continue;
    }
    for (const n of await revisionNumbers(dir)) {
      try {
        mans.push(JSON.parse(await fsp.readFile(path.join(dir, HIST, String(n), 'bundle.json'), 'utf8')));
      } catch {
        /* broken history folder */
      }
    }
    for (const m of mans) {
      const pv = m.provenance || {};
      results.push({
        result: `${REMOVED}/${d}`, revision: m.revision || 1, current: false, removed: true, issued: m.issued || null,
        result_id: m.result_id || null, module: m.module, module_version: pv.module_version || null,
        suite_version: pv.suite_version || null, source_sha256: pv.source_sha256 || {}, ...refsOf(m),
      });
    }
  }
  if (!results.length) return null;
  return {
    format: 'folio-lab-dependencies/1', report: id, created: new Date().toISOString(), results,
    note: 'Shared inputs (s-…) and project-index values (g-…) live in the Folio Lab project, not in this ZIP; the measurement files are under lab/<result>/source/. Results with removed: true were removed from the report after a revision was issued and are kept under lab/_removed/.',
  };
}

