def element_of(symbol: str) -> str:
    """'Fe3+' / 'O2-' / 'fe' / 'Fe1' -> 'Fe' (Ladung und Nummer weg, Schreibweise korrigiert)."""
    import re
    m = re.match(r"\s*([A-Za-z]{1,2})", str(symbol or ""))
    if not m:
        raise ValueError(f"Kein Element in „{symbol}“")
    s = m.group(1)
    for cand in (s[:1].upper() + s[1:2].lower(), s[:1].upper()):
        if cand in CM:
            return cand
    raise ValueError(f"Für „{symbol}“ ist kein Atomformfaktor hinterlegt (vorhanden: {', '.join(ELEMENTS)})")


def f0(element: str, s) -> np.ndarray:
    """Atomformfaktor bei s = sin θ / λ [1/Å] (Skalar oder Feld)."""
    co, _ = CM[element]
    s2 = np.asarray(s, dtype=float) ** 2
    out = co[8] + sum(co[2 * i] * np.exp(-co[2 * i + 1] * s2) for i in range(4))
    return out
