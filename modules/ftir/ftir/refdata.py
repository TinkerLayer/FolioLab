def band_model(bands, x: np.ndarray = GRID) -> np.ndarray:
    """Summe pseudo-Voigt-förmiger Banden (halb Gauss, halb Lorentz), Maximum 1."""
    y = np.zeros_like(x, dtype=float)
    for c, h, w in bands:
        t = (x - c) / (w / 2.0)
        y += h * (0.5 / (1 + t * t) + 0.5 * np.exp(-np.log(2) * t * t))
    return y / (y.max() or 1.0)


